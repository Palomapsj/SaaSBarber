// Shapes of the data returned by the API. Hand-written until the back-end publishes an
// OpenAPI spec; then these are replaced by generated types.

/** ISO 8601 timestamp in UTC, e.g. "2026-09-22T13:00:00Z". */
export type IsoDateTime = string;

/** 0 = Sunday … 6 = Saturday (same as Date.getDay). */
export type Weekday = 0 | 1 | 2 | 3 | 4 | 5 | 6;

/** Local time at the barbershop, "HH:mm". */
export type LocalTime = string;

/** Calendar date at the barbershop, "YYYY-MM-DD". */
export type LocalDate = string;

export type OpeningHours = {
  weekday: Weekday;
  opens: LocalTime;
  closes: LocalTime;
};

export type Address = {
  street: string;
  number: string;
  district: string;
  city: string;
  state: string;
};

export type Barbershop = {
  id: string;
  slug: string;
  name: string;
  address: Address;
  openingHours: OpeningHours[];
  /** Free cancellation or rescheduling up to this many hours before the appointment. */
  cancellationNoticeHours: number;
  /** Interval offered for automatic repetition; null when the barbershop does not offer it. */
  recurrenceIntervalWeeks: number | null;
  /** Subscription plan; limits how many barbers can be registered. */
  plan: { name: string; maxBarbers: number };
};

export type ServiceCategory = {
  id: string;
  name: string;
};

export type Service = {
  id: string;
  categoryId: string;
  name: string;
  durationMinutes: number;
  /** Price in cents (R$ 45,00 = 4500) to avoid floating point errors. */
  priceCents: number;
  /** Inactive services are not offered to clients (existing appointments keep them). */
  active: boolean;
};

/** A service as the admin sees it: plus who performs it. */
export type PanelService = Service & { barberIds: string[] };

/** Fields the admin sends to create or update a service. */
export type PanelServiceInput = {
  name: string;
  /** Category name; a new name creates the category. */
  categoryName: string;
  durationMinutes: number;
  priceCents: number;
  barberIds: string[];
  active: boolean;
};

export type PanelServicesPage = {
  categories: ServiceCategory[];
  services: PanelService[];
  barbers: { id: string; name: string; active: boolean }[];
};

/** Barber "Meus serviços": active services of the barbershop, marked with what this barber performs. */
export type BarberService = Service & { performed: boolean };

export type BarberServicesPage = {
  categories: ServiceCategory[];
  services: BarberService[];
};

export type ServiceCatalog = {
  categories: ServiceCategory[];
  services: Service[];
};

/** What clients see about a barber. */
export type Barber = {
  id: string;
  name: string;
  /** Categories of the services they perform, e.g. ["Cabelo", "Barba"] (generated by the API). */
  specialties: string[];
  serviceIds: string[];
  /** Inactive barbers do not appear for clients to book. */
  active: boolean;
};

/** What the admin sees and edits about a barber (never sent to clients). */
export type PanelBarber = Barber & {
  commissionPercent: number;
  /** Digits only. */
  phone: string;
  email: string;
};

/** Fields the admin sends to create or update a barber. */
export type PanelBarberInput = {
  name: string;
  commissionPercent: number;
  phone: string;
  email: string;
  serviceIds: string[];
  active: boolean;
};

export type PanelBarbersPage = {
  barbers: PanelBarber[];
  plan: { name: string; maxBarbers: number };
  categories: ServiceCategory[];
  services: Service[];
};

/** "Any barber" lets the back-end pick who attends when the booking is confirmed. */
export type BarberSelection = { kind: "any" } | { kind: "barber"; barberId: string };

export type AvailableDay = {
  date: LocalDate;
  /** False when the barbershop is open but every slot is taken. */
  hasFreeSlots: boolean;
};

export type TimeSlot = {
  startsAt: IsoDateTime;
  available: boolean;
};

export type AppointmentStatus = "confirmed" | "cancelled" | "completed";

export type Appointment = {
  id: string;
  barbershopId: string;
  status: AppointmentStatus;
  startsAt: IsoDateTime;
  durationMinutes: number;
  services: Pick<Service, "id" | "name">[];
  barber: Pick<Barber, "id" | "name">;
  totalCents: number;
  /** Set when the appointment repeats automatically. */
  recurrence: { everyWeeks: number } | null;
};

export type CreateAppointmentInput = {
  barbershopId: string;
  serviceIds: string[];
  barber: BarberSelection;
  startsAt: IsoDateTime;
  customer: { name: string; phone: string };
  recurring: boolean;
};

/** Code that gives the client access to "Meus agendamentos" (docs/adr/002). */
export type ClientAccess = { token: string; expiresAt: IsoDateTime };

export type CreatedAppointment = { appointment: Appointment; clientAccess: ClientAccess };

/** An appointment as the client sees it; the API says whether it can still be changed. */
export type MyAppointment = Appointment & {
  /** False when it is past, cancelled or inside the barbershop's cancellation notice. */
  canChange: boolean;
};

export type AgendaAppointment = {
  id: string;
  barberId: string;
  startsAt: IsoDateTime;
  durationMinutes: number;
  customerName: string;
  serviceNames: string[];
  status: AppointmentStatus;
  /** 0–3: which of the agenda colors (tokens event-1 to event-4) the card uses. */
  colorIndex: number;
};

export type DayHours = { opens: LocalTime; closes: LocalTime };

export type AgendaDay = {
  date: LocalDate;
  /** Null when the barbershop is closed that day. */
  hours: DayHours | null;
  barbers: { id: string; name: string; active: boolean }[];
  appointments: AgendaAppointment[];
  plan: { name: string; maxBarbers: number; barberCount: number };
};

export type BarberAgendaItem = {
  id: string;
  startsAt: IsoDateTime;
  durationMinutes: number;
  customerName: string;
  serviceNames: string[];
  status: AppointmentStatus;
};

export type BarberAgendaDay = {
  date: LocalDate;
  hours: DayHours | null;
  appointments: BarberAgendaItem[];
};

export type PanelRole = "admin" | "barber";

export type PanelUser = {
  id: string;
  role: PanelRole;
  barbershopId: string;
  barberId: string | null;
  name: string;
};
